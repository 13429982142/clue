const GEO_SUFFIX_REGEX = /(?:省|市|区|县|旗|乡|镇|村|工业园|园区|开发区|新区|街道|路|道|盟|州|大厦|路段|段|站)/;

/**
 * 判断一个文本是否为有效地理位置
 */
export function isValidLocation(text?: string | null): boolean {
  if (!text) return false;
  const str = text.trim();
  if (!str || str === '待核验地区' || str === '未知' || str === '0' || str === '无' || str.length < 2) {
    return false;
  }
  // 1. 如果能提取到明确省份，必是有效地点
  if (extractProvince(str)) {
    return true;
  }
  // 2. 含有典型行政区划后缀且长度在 2~30 之间
  if (GEO_SUFFIX_REGEX.test(str) && str.length >= 2 && str.length <= 40) {
    return true;
  }
  // 3. 纯数字、单个字、无意义测试字符过滤
  if (/^[\d\s\-_+=.,!@#$%^&*()，。！？、啊哦呃吧呢哈嘻呵测试]+$/.test(str)) {
    return false;
  }
  return false;
}

/**
 * 清洗并提取纯净的地点信息，去除“建设规模：”、“项目规模：”等混入的字段文本
 */
export function cleanLocation(rawLocation?: string | null): string {
  if (!rawLocation) return '';
  let str = rawLocation.trim();
  if (!str || str === '待核验地区' || str === '未知' || str === '0' || str.length < 2) return '';

  // 1. 去除前缀标签与引导词
  str = str.replace(
    /^(项目建设地点位于|项目地点位于|建设地点位于|工程建设地点位于|工程地点位于|项目建设地点|项目建设地区|建设地点|项目地点|所在地区|行政区域|工程地点|项目位于|建设位于|位于|在)[：:\s]*/,
    ''
  );
  str = str.replace(/^(\d{4}年(?:度)?|[一二三四五六七八九十\d]+[、.：:]|关于|建设)\s*/, '');

  // 2. 截断后续拼接的混杂字段标签
  const stopKeywords = [
    '建设项目规模', '建设规模', '项目建设规模', '项目规模', '工程规模', '主要规模',
    '项目建设内容', '建设内容', '工程内容', '主要建设内容', '建设主要内容', '项目概况',
    '主要招标范围', '主要招标内容', '招标范围', '标段划分', '采购需求', '合同履行',
    '计划工期', '工期要求', '工期', '质量要求', '出资比例', '资金来源', '出资方式', '资金落实',
    '投资估算', '总投资', '项目投资', '预算金额', '最高限价', '最高报价',
    '工程概况', '招标条件', '1.招标条件', '2.项目概况', '3.投标人', '3.1本次招标',
    '公告时间', '获取招标', '开标时间', '招标文件', '公告期限', '招标文件售价',
    '采购方式', '联系人', '联系电话', '项目名称', '采购人', '招标人', '建设单位', '代理机构',
    '每日上午', '每日下午', '获取招标文件的地点', '开标地点', '打印'
  ];
  for (const kw of stopKeywords) {
    const idx = str.indexOf(kw);
    if (idx >= 0) {
      str = str.substring(0, idx).trim();
    }
  }

  // 3. 去除末尾标点符号
  str = str.replace(/[；;，,。：:\s、]+$/, '').trim();

  // 4. 校验清洗后的有效性（避免 "啊"、纯数字等非地点字符被误展示）
  if (!isValidLocation(str)) {
    // 尝试从全文本提取省份，如果没有则认定为无效地点
    const prov = extractProvince(rawLocation);
    return prov || '';
  }

  // 5. 如果清洗后字符串过长（超过 30 个字），或者清洗后依然含有复杂工艺参数，尝试返回识别到的省份或截断
  if (str.length > 30) {
    const prov = extractProvince(str);
    if (prov) return prov;
    str = str.substring(0, 25) + '...';
  }

  return str;
}

/**
 * 综合提取一条商机线索的省份归属
 * 优先级：lead.region > lead.company > lead.title > lead.requirements
 */
export function getLeadProvince(lead?: {
  region?: string;
  company?: string;
  title?: string;
  requirements?: string;
} | null): string | null {
  if (!lead) return null;

  // 1. 行政区域字段
  if (lead.region && lead.region !== '待核验地区' && lead.region !== '未知') {
    const cleaned = cleanLocation(lead.region);
    if (cleaned) {
      const p = extractProvince(cleaned);
      if (p) return p;
    }
    const pDirect = extractProvince(lead.region);
    if (pDirect) return pDirect;
  }

  // 2. 发布单位/采购人字段 (通常含省/市/县级单位)
  if (lead.company && lead.company !== '待核验采购单位' && lead.company !== '未知') {
    const p = extractProvince(lead.company);
    if (p) return p;
  }

  // 3. 项目标题
  if (lead.title) {
    const p = extractProvince(lead.title);
    if (p) return p;
  }

  // 4. 需求/项目详情正文
  if (lead.requirements) {
    const p = extractProvince(lead.requirements);
    if (p) return p;
  }

  return null;
}

/**
 * 获取展示用的地点或省份
 */
export function getDisplayRegion(lead?: { region?: string; company?: string; title?: string; requirements?: string } | null): string {
  if (!lead) return '待核验地区';
  const cleaned = cleanLocation(lead.region);
  if (cleaned) return cleaned;
  const prov = getLeadProvince(lead);
  return prov || '待核验地区';
}


