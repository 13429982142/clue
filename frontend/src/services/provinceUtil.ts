// 预排好序的别名和地名键列表（长度降序保证长词优先）
const SORTED_PROVINCES = [...PROVINCES_STANDARD].sort((a, b) => b.length - a.length);
const SORTED_PROVINCE_ALIASES = Object.keys(PROVINCE_ALIAS).sort((a, b) => b.length - a.length);
const SORTED_REGION_ALIASES = Object.keys(REGION_ALIAS).sort((a, b) => b.length - a.length);

/**
 * 从单段文本中精确提取标准化省份全称
 * 彻底过滤 "2026年"、"年广东省" 等错误前缀
 */
export function extractProvince(text?: string | null): string | null {
  if (!text) return null;
  let raw = text.trim();
  if (!raw) return null;

  // 1. 去除年份、杂质前缀 (如 2026年、关于、建设地点：等)
  raw = raw.replace(/^(\d{4}年(?:度)?|[一二三四五六七八九十\d]+[、.：:]|关于|位于|在|项目地点[：:]|建设地点[：:]|行政区域[：:]|地区[：:])\s*/, '');

  // 2. 优先匹配 34 个官方省/市/自治区全称
  for (const p of SORTED_PROVINCES) {
    if (raw.includes(p)) {
      return p;
    }
  }

  // 3. 匹配省份简称/别名（如 广东 -> 广东省，新疆 -> 新疆维吾尔自治区）
  for (const key of SORTED_PROVINCE_ALIASES) {
    if (raw.includes(key)) {
      return PROVINCE_ALIAS[key];
    }
  }

  // 4. 匹配地级市/区县/乡镇（如 桐庐/莼山/杭州 -> 浙江省，鄯善/吐鲁番 -> 新疆维吾尔自治区）
  for (const key of SORTED_REGION_ALIASES) {
    if (raw.includes(key)) {
      return REGION_ALIAS[key];
    }
  }

  // 5. 正则精准兜底匹配省/自治区（严格去除前面的非省份汉字如"年"）
  const regexMatch = raw.match(/(?:^|[^\u4e00-\u9fff]|年|度|在|于|及|和|关于|建设)?([\u4e00-\u9fff]{2,5}(?:省|自治区|特别行政区))/);
  if (regexMatch && regexMatch[1]) {
    let candidate = regexMatch[1];
    // 清理可能附带的单个字前缀
    candidate = candidate.replace(/^(年|度|在|于|及|和|省|市)/, '');
    if (candidate in PROVINCE_ALIAS) {
      return PROVINCE_ALIAS[candidate];
    }
    if (candidate.endsWith('省') || candidate.endsWith('自治区') || candidate.endsWith('特别行政区')) {
      return candidate;
    }
  }

  return null;
}

